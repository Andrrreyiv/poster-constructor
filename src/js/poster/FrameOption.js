// FrameOption — физическая рама, в которую вставляется готовая пластина.
//
// ☠️ ИМЯ ВЫБРАНО СПЕЦИАЛЬНО. У конструктора футболок есть PrintFrame.js, и это
// СОВСЕМ ДРУГОЕ: там «рамка» — это зона печати, clip-область на мокапе. Если назвать
// модуль так же, следующая сессия перепутает понятия. Здесь рама — предмет из пластика
// или дерева, надеваемый на пластину снаружи.
//
// Клиент 13.09 (голосовое 10:27), дословно: «рамка физическая обычная, то есть смотрите,
// это железная пластина алюминиевая, на неё наносится картинка, и можно эту картинку
// в рамку поставить, рамка обычная пластиковая или деревянная… надо добавить кнопку
// с рамкой / без рамки… и сделать вариации рамки: белая, чёрная и под дерево».
//
// ⚠️ Это ОПРОВЕРГАЕТ решение, записанное в плане до голосового: там рама считалась
// рисуемой обводкой ПОВЕРХ картинки (ширина + цвет). Рама физическая, значит она
// обрамляет пластину СНАРУЖИ, а картинка остаётся во всю пластину и ничем не
// перекрывается. Геометрия ниже именно такая.
//
// Рисуется рама НАКЛАДНОЙ КАРТИНКОЙ (PNG с прозрачной серединой), а не заливкой:
// заливкой невозможно показать ни волокно дерева, ни блик на пластике, а покупатель
// выбирает раму именно глазами. Заливка осталась запасным вариантом в PosterCanvas
// на случай, когда текстура не доехала. Когда клиент пришлёт фотографии своих рам,
// меняются только три файла в assets/frames — код не трогается.

/** Список рам из конфига. Пустой список = опция рамы просто не показывается. */
export function frameList(config) {
  if (config?.frames?.enabled === false) return [];
  return config?.frames?.options ?? [];
}

/** Рама по id. null — это «без рамы», законное состояние, а не ошибка. */
export function frameById(config, id) {
  if (id === null || id === undefined) return null;
  return frameList(config).find((f) => f.id === id) ?? null;
}

/**
 * Цена рамы ДЛЯ КОНКРЕТНОЙ ПЛАСТИНЫ.
 *
 * Клиент 19.09 (голосовое 08:59), дословно: «под каждую пластину рама соответственно
 * увеличивается и цена у неё другая… если я не проставил под дерево, то в конструкторе
 * рама под дерево не отображается. Это значит её нету в наличии».
 *
 * Отсюда два правила, и второе важнее первого:
 *   - цена ищется в карте prices по id пластины;
 *   - ☠️ НЕТ ЦЕНЫ — НЕТ РАМЫ. Пустая клетка это не «бесплатно», а «под этот размер
 *     такой рамы нет», и рама не показывается покупателю вовсе.
 *
 * Пока карты prices нет вообще (базовый конфиг до первого сохранения админки),
 * работает прежняя плоская цена: иначе конструктор остался бы без рам ровно до того
 * момента, как владелец заполнит таблицу, а он собирался сделать это «попозже».
 *
 * @returns {number|null} null = рамы под этот размер нет
 */
export function framePriceFor(config, frameId, plateId) {
  const frame = frameById(config, frameId);
  if (!frame) return null;

  if (frame.prices && typeof frame.prices === 'object' && !Array.isArray(frame.prices)) {
    const v = Number(frame.prices[plateId]);
    return Number.isFinite(v) && v >= 0 ? v : null;
  }

  const flat = Number(frame.price);
  return Number.isFinite(flat) && flat >= 0 ? flat : null;
}

/**
 * Рамы, доступные под эту пластину, уже с ценой. Именно этот список видит покупатель.
 * Пустой список значит, что под выбранный размер рам нет ни одной.
 */
export function framesForPlate(config, plateId) {
  return frameList(config)
    .map((f) => ({ ...f, price: framePriceFor(config, f.id, plateId) }))
    .filter((f) => f.price !== null);
}

